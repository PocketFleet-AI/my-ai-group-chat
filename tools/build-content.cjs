#!/usr/bin/env node
// Assemble source sections into the original single lexical scope. No runtime loader.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '..');
const extension = path.join(root, 'browser-extension');
const output = path.join(extension, 'content_bundle.js');
const marker = /^\/\/ @content-section ([a-z0-9-]+)\n/gm;

function assembleContent() {
  const plan = JSON.parse(fs.readFileSync(path.join(extension, 'content_assembly.json'), 'utf8'));
  if (plan.formatVersion !== 1 || !Array.isArray(plan.sections) || !plan.sections.length) {
    throw new Error('Invalid content assembly plan');
  }
  const sections = new Map();
  for (const file of new Set(plan.sections.map(section => section.file))) {
    const absolute = path.resolve(extension, file);
    if (!absolute.startsWith(extension + path.sep) || !file.endsWith('.js')) {
      throw new Error('Invalid content source path: ' + file);
    }
    const source = fs.readFileSync(absolute, 'utf8').replace(/\r\n/g, '\n');
    // Source modules must also be syntactically valid in isolation (not executed).
    new vm.Script(source, { filename: file });
    const matches = [...source.matchAll(marker)];
    if (!matches.length || source.slice(0, matches[0].index).trim() !== '') {
      throw new Error('Content outside named sections: ' + file);
    }
    for (let i = 0; i < matches.length; i++) {
      const id = matches[i][1];
      const body = source.slice(matches[i].index + matches[i][0].length, matches[i + 1]?.index ?? source.length);
      if (sections.has(id)) throw new Error('Duplicate content section: ' + id);
      sections.set(id, { file, body });
    }
  }
  const used = new Set();
  const body = plan.sections.map(section => {
    const found = sections.get(section.id);
    if (!found || found.file !== section.file || used.has(section.id)) {
      throw new Error('Missing, misplaced or repeated section: ' + section.id);
    }
    used.add(section.id);
    return found.body;
  }).join('');
  if (used.size !== sections.size) throw new Error('Unlisted content sections');
  const code = '// GENERATED by tools/build-content.cjs. Edit source modules, not this file.\n(() => {\n' + body + '})();\n';
  new vm.Script(code, { filename: 'content_bundle.js' });
  return { code, body, plan };
}

function buildContent({ check = false } = {}) {
  const result = assembleContent();
  if (check) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== result.code) {
      throw new Error('content_bundle.js is stale; run node tools/build-content.cjs');
    }
  } else {
    fs.writeFileSync(output, result.code, 'utf8');
  }
  return result;
}

if (require.main === module) {
  try {
    const result = buildContent({ check: process.argv.includes('--check') });
    if (process.argv.includes('--verify-baseline')) {
      const hash = crypto.createHash('sha256').update(result.body).digest('hex');
      if (hash !== result.plan.baseline.normalizedBodySha256) {
        throw new Error('Assembled body differs from the initial split baseline');
      }
      console.log('Initial split baseline body is unchanged: ' + hash);
    }
    console.log(`Content ${process.argv.includes('--check') ? 'checked' : 'built'}: ${result.plan.sections.length} sections, one closure`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
module.exports = { assembleContent, buildContent };
